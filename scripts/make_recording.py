#!/usr/bin/env python3
"""Merge the three trace files of a recorded run into docs/visualization/recording.js.

  mx_exchange --trace trace.csv ...     engine: commands, acks, fills, cancels, trades
  mx_mm       --events mm.csv ...       maker: mid, quotes, inventory, PnL at every quote update
  mx_flow     --events flow.csv ...     simulator: the fundamental value

All three use the same monotonic clock, so they line up without adjustment.
Usage: make_recording.py trace.csv mm.csv flow.csv out.js
"""
import json, sys

trace, mm, flow, out = sys.argv[1:5]
CODE = {"N": 0, "A": 1, "X": 2, "F": 3, "K": 4, "T": 5}
rows = [l.rstrip("\n").split(",") for l in open(trace) if l.strip()]
q = [l.rstrip("\n").split(",") for l in open(mm) if l.strip()]
v = [l.rstrip("\n").split(",") for l in open(flow) if l.strip()]
t0 = min(int(rows[0][1]), int(q[0][1]), int(v[0][1]))
ms = lambda ns: round((int(ns) - t0) / 1e6, 1)

ids = {}                      # 64-bit exchange order ids -> small integers (JS numbers are doubles)
def oid(x):
    return ids.setdefault(x, len(ids) + 1)

ev = []
for r in rows:
    k, t = r[0], ms(r[1])
    if k == "N":   ev.append([0, t, int(r[2]), int(r[3]), int(r[4]), int(r[5]), int(r[6]), int(r[7])])  # client side px qty tif type
    elif k == "A": ev.append([1, t, int(r[2]), oid(r[3])])
    elif k == "X": ev.append([2, t, int(r[2]), oid(r[3])])
    elif k == "F": ev.append([3, t, int(r[2]), oid(r[3]), int(r[4]), int(r[5]), int(r[6]), int(r[7]), int(r[8])])  # client oid px qty leaves side maker
    elif k == "K": ev.append([4, t, int(r[2]), oid(r[3]), int(r[4]), int(r[5])])  # client oid qty reason
    elif k == "T": ev.append([5, t, int(r[2]), int(r[3]), int(r[4])])  # px qty aggressor

rec = {
    "duration": max(ev[-1][1], ms(q[-1][1])),
    "ev": ev,
    "q": [[ms(r[1]), float(r[2]), int(r[3]), int(r[4]), int(r[5]), float(r[6]), float(r[7])] for r in q],  # t mid bid ask inv pnl reservation
    "v": [[ms(r[1]), float(r[2])] for r in v],
}
with open(out, "w") as f:
    f.write("// Generated by scripts/make_recording.py from a real run of mx_exchange, mx_mm and mx_flow.\n")
    f.write("window.RECORDING = " + json.dumps(rec, separators=(",", ":")) + ";\n")
print(f"{len(ev)} engine events, {len(rec['q'])} maker updates, {rec['duration'] / 1000:.1f} s -> {out}")
